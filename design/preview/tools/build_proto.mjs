// Collects every [data-go] hotspot of every screen into preview/proto.js for prototype.html (and Figma reactions).
// Run: node design/preview/tools/build_proto.mjs
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const { chromium } = createRequire(import.meta.url)('playwright');
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const pages = fs.readdirSync(root).filter((f) => f.startsWith('screens-') && f.endsWith('.html')).sort();
const browser = await chromium.launch();
const p = await browser.newPage({ viewport: { width: 3400, height: 1000 } });
const screens = {};
for (const page of pages) {
  await p.goto(pathToFileURL(path.join(root, page)).href);
  await p.evaluate(() => document.fonts.ready);
  const found = await p.evaluate(() => [...document.querySelectorAll('[data-shot$="_light"]')].map((ph) => {
    const r = ph.getBoundingClientRect();
    return {
      id: ph.dataset.shot.replace(/_light$/, ''),
      caption: ph.parentElement.querySelector('.cap')?.textContent || '',
      hotspots: [...ph.querySelectorAll('[data-go]')].map((el) => {
        const b = el.getBoundingClientRect();
        return { x: Math.round(b.left - r.left), y: Math.round(b.top - r.top), w: Math.round(b.width), h: Math.round(b.height), go: el.dataset.go };
      }),
    };
  }));
  for (const s of found) screens[s.id] = { page, caption: s.caption, hotspots: s.hotspots };
}
await browser.close();
const missing = Object.values(screens).flatMap((s) => s.hotspots.map((h) => h.go)).filter((g) => !screens[g]);
if (missing.length) { console.error('Unknown targets:', [...new Set(missing)]); process.exitCode = 1; }
fs.writeFileSync(path.join(root, 'proto.js'), '// GENERATED by tools/build_proto.mjs. Do not edit.\nwindow.PROTO = ' + JSON.stringify(screens, null, 1) + ';\n');
console.log(Object.keys(screens).length, 'screens,', Object.values(screens).reduce((n, s) => n + s.hotspots.length, 0), 'hotspots');
